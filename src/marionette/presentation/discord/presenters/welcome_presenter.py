class WelcomePresenter:
    @staticmethod
    def present_welcome(user_mention: str) -> str:
        return f"Поприветствуем {user_mention}! " + \
                "Как минимум, первый этап прохождения ему или ей, а может и чему-то ещё оказался весьма простым.\n" + \
                "Впрочем, могу лишь посоветовать повторно ознакомиться с правилами, а ответ на вопросы \"куда я попал?\" лежит в введении, которое ты, скорее всего, упускаешь."
